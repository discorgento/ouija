package main

import (
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func mustWrite(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

func TestFindSubPackages(t *testing.T) {
	root := t.TempDir()

	mustWrite(t, filepath.Join(root, "task", "task.go"), "package task\n")
	mustWrite(t, filepath.Join(root, "doc", "doc.go"), "package doc\n")
	mustWrite(t, filepath.Join(root, "sticker", "sticker.go"), "package sticker\n")
	mustWrite(t, filepath.Join(root, "sticker", "imports_gen.go"), "package sticker\n")
	mustWrite(t, filepath.Join(root, "totems.go"), "package totems\n") // files at the root are not sub-packages
	mustWrite(t, filepath.Join(root, "notes", "README.md"), "not go\n")
	mustWrite(t, filepath.Join(root, ".hidden", "hidden.go"), "package hidden\n")
	mustWrite(t, filepath.Join(root, "_vendor", "vendor.go"), "package vendor\n")
	mustWrite(t, filepath.Join(root, "cache", "imports_gen.go"), "package cache\n") // only the output file

	got, err := findSubPackages(root, "imports_gen.go")
	if err != nil {
		t.Fatalf("findSubPackages() error = %v", err)
	}

	want := []string{"doc", "sticker", "task"} // sorted; notes/.hidden/_vendor/cache excluded
	if len(got) != len(want) {
		t.Fatalf("findSubPackages() = %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("findSubPackages() = %v, want %v", got, want)
		}
	}
}

func TestFindSubPackages_MissingRoot(t *testing.T) {
	if _, err := findSubPackages(filepath.Join(t.TempDir(), "nope"), "imports_gen.go"); err == nil {
		t.Error("findSubPackages() error = nil for a missing root, want an error")
	}
}

func TestDirContainsGoFiles(t *testing.T) {
	dir := t.TempDir()

	if got, err := dirContainsGoFiles(dir, "imports_gen.go"); err != nil || got {
		t.Fatalf("empty dir = (%v, %v), want (false, nil)", got, err)
	}

	mustWrite(t, filepath.Join(dir, "notes.txt"), "x")
	if got, _ := dirContainsGoFiles(dir, "imports_gen.go"); got {
		t.Error("a directory holding only a .txt file was reported as a Go package")
	}

	mustWrite(t, filepath.Join(dir, "imports_gen.go"), "package x\n")
	if got, _ := dirContainsGoFiles(dir, "imports_gen.go"); got {
		t.Error("the output file itself must not count as a package")
	}

	mustWrite(t, filepath.Join(dir, "real.go"), "package x\n")
	if got, _ := dirContainsGoFiles(dir, "imports_gen.go"); !got {
		t.Error("a directory with a real .go file was not detected")
	}
}

// writeGenFile must emit imports with the real module path. A module rename
// that misses this file produces a binary with zero totems registered, which
// `make check` cannot catch on its own.
func TestWriteGenFile_UsesModulePath(t *testing.T) {
	path := filepath.Join(t.TempDir(), "imports_gen.go")

	if err := writeGenFile(path, "totems", []string{"doc", "task"}); err != nil {
		t.Fatalf("writeGenFile() error = %v", err)
	}
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}

	got := string(b)
	for _, want := range []string{
		"// Code generated by genimports; DO NOT EDIT.",
		"package totems",
		`_ "github.com/discorgento/ouija/totems/doc"`,
		`_ "github.com/discorgento/ouija/totems/task"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("generated file is missing %q:\n%s", want, got)
		}
	}

	if _, err := format.Source(b); err != nil {
		t.Errorf("generated file is not valid Go: %v", err)
	}
}
