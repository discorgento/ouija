// Command genimports scans a directory for sub-packages and generates a Go file
// with blank imports for each one. It is invoked by go:generate directives.
//
// Usage:
//
//	go run ../internal/tools/genimports -dir <dir> -out <file> -pkg <name>
//
// It walks the given directory, finds every subdirectory that contains at least
// one .go file (other than the output file itself), and writes a Go file with
// a blank import for each one.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	dir := flag.String("dir", ".", "directory to scan for sub-packages")
	out := flag.String("out", "imports_gen.go", "output file name")
	pkg := flag.String("pkg", "totems", "package name for the generated file")
	flag.Parse()

	pkgs, err := findSubPackages(*dir, *out)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
	if len(pkgs) == 0 {
		fmt.Fprintf(os.Stderr, "warning: no sub-packages found in %s\n", *dir)
	}

	genPath := filepath.Join(*dir, *out)
	if err := writeGenFile(genPath, *pkg, pkgs); err != nil {
		fmt.Fprintf(os.Stderr, "error writing %s: %v\n", genPath, err)
		os.Exit(1)
	}
}

// findSubPackages lists subdirectories of root that contain at least one .go
// file (ignoring the output file name).
func findSubPackages(root, ignoreFile string) ([]string, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		return nil, err
	}
	var pkgs []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		name := e.Name()
		if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
			continue
		}
		dir := filepath.Join(root, name)
		hasGo, err := dirContainsGoFiles(dir, ignoreFile)
		if err != nil {
			return nil, err
		}
		if hasGo {
			pkgs = append(pkgs, name)
		}
	}
	slices.Sort(pkgs)
	return pkgs, nil
}

// dirContainsGoFiles reports whether dir contains any .go file whose base name
// differs from ignoreFile (to avoid counting the output file itself).
func dirContainsGoFiles(dir, ignoreFile string) (bool, error) {
	files, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	for _, f := range files {
		if f.IsDir() {
			continue
		}
		name := f.Name()
		if strings.HasSuffix(name, ".go") && name != ignoreFile {
			return true, nil
		}
	}
	return false, nil
}

// writeGenFile creates a Go file with blank imports for each discovered package.
func writeGenFile(path, pkg string, pkgs []string) error {
	var b strings.Builder
	b.WriteString("// Code generated by genimports; DO NOT EDIT.\n")
	b.WriteString(fmt.Sprintf("package %s\n\n", pkg))
	b.WriteString("import (\n")
	for _, p := range pkgs {
		b.WriteString(fmt.Sprintf("\t_ \"github.com/discorgento/ouija/totems/%s\"\n", p))
	}
	b.WriteString(")\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
